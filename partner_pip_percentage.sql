    ('68c421dee92eeb0023920518', 'Pavithra ma''am'),
    ('69231c3fd6991900259e7286', 'Pavithra ma''am'),
    ('685e4f0dbd3942002680ed8a', 'Pavithra ma''am') AS t(provider_id, trainer_name)
),
churn_cte AS (
  SELECT
    DISTINCT pdf.provider_id,
    CASE
      WHEN COALESCE(l7d.L7D_status, 'Unknown') = 'Not Working' THEN 'churn'
      ELSE 'active'
    END AS churn_status
  FROM
    provider__daily__facts pdf
    LEFT JOIN (
      SELECT
        acm.provider_id,
        CASE
          WHEN SUM(
            CASE
              WHEN acm.status = 'marked working' THEN 1
              ELSE 0
            END
          ) > 4 THEN 'Working'
          ELSE 'Not Working'
        END AS L7D_status
      FROM
        PUBLIC.providerXdateXhour__calendar_marking__hourly__facts acm
      WHERE
        DATE(acm.date) BETWEEN CURRENT_DATE - 6
        AND CURRENT_DATE
        AND acm.start_hour_local BETWEEN 8
        AND 19
      GROUP BY
        acm.provider_id
    ) l7d ON l7d.provider_id = pdf.provider_id
  WHERE
    pdf.customer_category_key = 'insta_maids'
    AND pdf.approval_date >= '2025-02-01'
    AND pdf.country = 'India'
),
base AS (
  SELECT
    tm.trainer_name AS tm,
    DATE_TRUNC('WEEK', DATE(acm.date)) AS perf_week,
    acm.provider_id,
    c.churn_status
  FROM
    PUBLIC.providerXdateXhour__calendar_marking__hourly__facts acm
    JOIN trainer_mapping tm ON acm.provider_id = tm.provider_id
    LEFT JOIN churn_cte c ON acm.provider_id = c.provider_id
  WHERE
    acm.start_hour_local BETWEEN 8
    AND 19
    AND DATE(acm.date) <= CURRENT_DATE
),
ranked_ratings AS (
  SELECT
    m.provider_id,
    m.rating,
    ROW_NUMBER() OVER (
      PARTITION BY m.provider_id
      ORDER BY
        m.bdate DESC
    ) AS rating_rank
  FROM
    public.MASTER_DATA_EXPLORE_TABLE m
  WHERE
    m.rating IS NOT NULL
    AND m.service_delivered = 1
),
avg_rating_last_50 AS (
  SELECT
    r.provider_id,
    ROUND(
      SUM(r.rating) / NULLIF(COUNT(r.rating), 0),
      2
    ) AS avg_rating_50
  FROM
    ranked_ratings r
  WHERE
    r.rating_rank <= 50
  GROUP BY
    r.provider_id
),
weekly_ratings AS (
  SELECT
    tm.trainer_name AS tm,
    DATE_TRUNC('WEEK', m.bdate) AS perf_week,
    m.provider_id,
    m.rating
  FROM
    public.MASTER_DATA_EXPLORE_TABLE m
    JOIN trainer_mapping tm ON m.provider_id = tm.provider_id
  WHERE
    m.rating IS NOT NULL
    AND m.service_delivered = 1
),
weekly_rating_tm AS (
  SELECT
    tm,
    perf_week,
    ROUND(AVG(rating), 2) AS weekly_avg_rating,
    COUNT(*) AS total_ratings
  FROM
    weekly_ratings
  GROUP BY
    tm,
    perf_week
),
tier_base AS (
  SELECT
    ppm.provider_id,
    ppm.tier_start_date,
    ppm.tier_end_date,
    DATE_TRUNC('week', ppm.tier_end_date) AS perf_week_tier,
    ppm.GRADED_LEAVE_DAYS_AT_TIER AS leave_days,
    ROW_NUMBER() OVER (
      PARTITION BY ppm.provider_id
      ORDER BY
        ppm.tier_start_date DESC
    ) AS rn_desc
  FROM
    PROVIDER_PROMISE_PLAN__DAILY__METRICS ppm
  WHERE
    ppm.CATEGORY = 'instant_maids_l3'
    AND ppm.tier_status IN ('active', 'completed')
    AND ppm.tier IS NOT NULL
    AND ppm.CUSTOMER_CATEGORY_KEY = 'insta_maids'
),
latest_tier AS (
  SELECT
    provider_id,
    tier_start_date,
    tier_end_date,
    perf_week_tier,
    leave_days
  FROM
    tier_base
  WHERE
    rn_desc = 1
),
late_shows AS (
  SELECT
    mdet.provider_id,
    COUNT(DISTINCT mdet.customer_request_id) AS late_show_count
  FROM
    PUBLIC.MASTER_DATA_EXPLORE_TABLE mdet
    JOIN latest_tier lt ON mdet.provider_id = lt.provider_id
    AND DATE(mdet.bdate) BETWEEN lt.tier_start_date
    AND lt.tier_end_date
  WHERE
    mdet.revised_start_at IS NOT NULL
    AND mdet.bdate IS NOT NULL
    AND mdet.service_delivered = 1
    AND DATEDIFF('minute', mdet.bdate, mdet.revised_start_at) > 5
  GROUP BY
    mdet.provider_id
),
tm_avg_leave AS (
  SELECT
    tm.trainer_name AS tm,
    ROUND(AVG(lt.leave_days), 2) AS avg_marked_leave
  FROM
    latest_tier lt
    JOIN trainer_mapping tm ON lt.provider_id = tm.provider_id
  GROUP BY
    tm
),
tm_avg_late_show AS (
  SELECT
    tm.trainer_name AS tm,
    ROUND(
      AVG(COALESCE(ls.late_show_count, 0)),
      2
    ) AS avg_late_show
  FROM
    latest_tier lt
    JOIN trainer_mapping tm ON lt.provider_id = tm.provider_id
    LEFT JOIN late_shows ls ON lt.provider_id = ls.provider_id
  GROUP BY
    tm
),
paf_base AS (
  SELECT
    tm.trainer_name AS tm,
    DATE_TRUNC('WEEK', DATE(mdet.bdate)) AS perf_week,
    mdet.provider_id,
    COUNT(DISTINCT mdet.customer_request_id) AS total_requests,
    COUNT(
      DISTINCT CASE
        WHEN paf.ns_provider_at_fault_flag = 1 THEN mdet.customer_request_id
      END
    ) AS paf_requests
  FROM
    PUBLIC.MASTER_DATA_EXPLORE_TABLE mdet
    LEFT JOIN REQUEST__BCE__HOURLY__FACTS paf ON mdet.customer_request_id = paf.customer_request_id
    JOIN trainer_mapping tm ON mdet.provider_id = tm.provider_id
  WHERE
    mdet.customer_category_key = 'insta_maids'
    AND mdet.bdate IS NOT NULL
  GROUP BY
    tm,
    perf_week,
    mdet.provider_id
),
paf_provider AS (
  SELECT
    paf.provider_id,
    COUNT(
      DISTINCT CASE
        WHEN paf.ns_provider_at_fault_flag = 1 THEN rhf.customer_request_id
      END
    ) AS paf_cancels
  FROM
    request__hourly__facts rhf
    JOIN REQUEST__BCE__HOURLY__FACTS paf ON rhf.customer_request_id = paf.customer_request_id
    JOIN latest_tier lt ON paf.provider_id = lt.provider_id
    AND DATE(rhf.bdate) BETWEEN lt.tier_start_date
    AND lt.tier_end_date
  WHERE
    rhf.customer_category_key = 'insta_maids'
  GROUP BY
    paf.provider_id
),
paf_tm_week AS (
  SELECT
    tm,
    perf_week,
    ROUND(
      100.0 * SUM(paf_requests) / NULLIF(SUM(total_requests), 0),
      2
    ) AS paf_pct
  FROM
    paf_base
  GROUP BY
    tm,
    perf_week
),
pip_base AS (
  SELECT
    lt.provider_id,
    COALESCE(lt.leave_days, 0) AS leave_days,
    COALESCE(pp.paf_cancels, 0) AS cancels,
    COALESCE(ls.late_show_count, 0) AS late_shows,
    COALESCE(ar.avg_rating_50, 0) AS l50_rating,
    lt.perf_week_tier,
    CASE
      WHEN COALESCE(lt.leave_days, 0) >= 5
        OR COALESCE(pp.paf_cancels, 0) >= 4
        OR (ar.avg_rating_50 IS NOT NULL AND ar.avg_rating_50 < 4.7)
        OR COALESCE(ls.late_show_count, 0) >= 5
      THEN 1
      ELSE 0
    END AS is_pip
  FROM
    latest_tier lt
    LEFT JOIN avg_rating_last_50 ar ON lt.provider_id = ar.provider_id
    LEFT JOIN late_shows ls ON lt.provider_id = ls.provider_id
    LEFT JOIN paf_provider pp ON lt.provider_id = pp.provider_id
),
active_partners AS (
  SELECT
    tm.trainer_name AS tm,
    COUNT(DISTINCT CASE
      WHEN COALESCE(c.churn_status, 'active') <> 'churn'
      THEN tm.provider_id
    END) AS total_active_px
  FROM
    trainer_mapping tm
    LEFT JOIN churn_cte c ON tm.provider_id = c.provider_id
  GROUP BY
    tm.trainer_name
),
pip_tm AS (
  SELECT
    tm.trainer_name AS tm,
    pb.perf_week_tier,
    COUNT(DISTINCT CASE
      WHEN pb.is_pip = 1
       AND COALESCE(c.churn_status, 'active') <> 'churn'
      THEN pb.provider_id
    END) AS pip_px,
    MAX(ap.total_active_px) AS active_px
  FROM
    pip_base pb
    JOIN trainer_mapping tm ON pb.provider_id = tm.provider_id
    LEFT JOIN churn_cte c ON pb.provider_id = c.provider_id
    LEFT JOIN active_partners ap ON tm.trainer_name = ap.tm
  GROUP BY
    tm.trainer_name,
    pb.perf_week_tier
)
SELECT
  b.tm AS "TMs",
  b.perf_week AS "Perf Week",
  COUNT(DISTINCT b.provider_id) AS "Total PX",
  COUNT(
    DISTINCT CASE
      WHEN b.churn_status = 'churn' THEN b.provider_id
    END
  ) AS "Churn PX",
  ROUND(AVG(ag.avg_rating_50), 2) AS "L50 Rating",
  MAX(wr.weekly_avg_rating) AS "Weekly Avg Rating",
  MAX(tl.avg_marked_leave) AS "Avg Leave / PX",
  MAX(ls.avg_late_show) AS "Avg Late Shows / PX",
  MAX(pw.paf_pct) AS "PAF %",
  ROUND(
    100.0 * MAX(pt.pip_px) / NULLIF(MAX(pt.active_px), 0),
    2
  ) AS "PIP %"
FROM
  base b
  LEFT JOIN avg_rating_last_50 ag ON b.provider_id = ag.provider_id
  LEFT JOIN weekly_rating_tm wr ON b.tm = wr.tm
  AND b.perf_week = wr.perf_week
  LEFT JOIN tm_avg_leave tl ON b.tm = tl.tm
  LEFT JOIN tm_avg_late_show ls ON b.tm = ls.tm
  LEFT JOIN paf_tm_week pw ON b.tm = pw.tm
  AND b.perf_week = pw.perf_week
  LEFT JOIN pip_tm pt ON b.tm = pt.tm
  AND b.perf_week = pt.perf_week_tier
GROUP BY
  1,
  2
ORDER BY
  2 DESC,
  1;
